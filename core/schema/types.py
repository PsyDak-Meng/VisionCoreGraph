"""Schema-as-code (SPEC §4.5) and the extraction contract (SPEC §4.3)."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Literal

from pydantic import BaseModel, Field, field_validator


@dataclass(frozen=True)
class InstantRelation:
    name: str
    subject: str
    object: str | tuple[str, ...]


@dataclass(frozen=True)
class DurativeRelation:
    name: str
    subject: str
    object: str | tuple[str, ...]
    opens_on: tuple[str, ...]
    closes_on: tuple[str, ...]
    cardinality: Literal["one_subject_per_object", "unconstrained"] = "unconstrained"


@dataclass(frozen=True)
class SkillSchema:
    name: str
    entity_classes: tuple[str, ...]
    instant_relations: tuple[InstantRelation, ...] = field(default_factory=tuple)
    durative_relations: tuple[DurativeRelation, ...] = field(default_factory=tuple)

    @property
    def relation_names(self) -> set[str]:
        """Every relation a *query* may mention. Extraction uses the narrower set below."""
        return {r.name for r in self.instant_relations} | {r.name for r in self.durative_relations}

    @property
    def instant_relation_names(self) -> set[str]:
        """The only relations the VLM may emit.

        Durative relations are derived by the StateReducer from the instants that open and close
        them (D10); offering them to the VLM lets it report a state it sees instead of the
        transition it should be watching for. Measured on object_transfer.mp4: with POSSESSES in
        the vocabulary the model emitted it for six people against one bag in a single frame and
        never once emitted PICKS_UP, DROPS or HANDS_OFF. Same reasoning as D6, one level up:
        the VLM owns observations, the reducer owns intervals.
        """
        return {r.name for r in self.instant_relations}

    def operands_conform(self, relation: str, subject_class: str, object_class: str) -> bool:
        """Whether a relation's operand classes match what the schema declares for it.

        The VLM picks verbs from a closed vocabulary (make_semantic_delta_model) but names operands
        by Set-of-Mark id, so nothing in the extraction contract can stop it emitting
        HANDS_OFF(person, person) when the schema says the object must be a bag. Checking here is
        what keeps §6.5 honest: an unrepresentable edge is rejected loudly, not stored.
        """
        for r in self.instant_relations + self.durative_relations:
            if r.name != relation:
                continue
            objects = r.object if isinstance(r.object, tuple) else (r.object,)
            subjects = r.subject if isinstance(r.subject, tuple) else (r.subject,)
            return subject_class in subjects and object_class in objects
        return False

    def durative_for(self, event_relation: str) -> list[DurativeRelation]:
        """Durative relations opened or closed by an instant relation name."""
        return [
            d for d in self.durative_relations
            if event_relation in d.opens_on or event_relation in d.closes_on
        ]


class Entity(BaseModel):
    """Echoed from the detector for provenance — never generated by the VLM (D4)."""

    local_id: str
    class_label: str
    bbox: list[int] = Field(description="[x_min, y_min, x_max, y_max]")


class VLMRelation(BaseModel):
    """What the VLM is allowed to emit: a relation between two ids it was given, nothing else.

    Deliberately carries NO timestamp. The model sees one frame and is never told what time it is,
    so any timestamp it produced would be invented — and the reducer would then anchor real interval
    boundaries to that invention. Absent-from-the-schema is a stronger guarantee than ignore-the-field
    (same reasoning as D6, which keeps the VLM out of valid_from/valid_until for this exact reason).
    Timestamps are stamped from the frame at extraction time; see TemporalEdge.
    """

    source_id: str
    target_id: str
    relation: str = Field(description="Action verb from the schema's relation vocabulary")


class TemporalEdge(BaseModel):
    """Internal event record. `timestamp` is the keyframe's real presentation time, never model output."""

    source_id: str
    target_id: str
    relation: str
    timestamp: float
    src_frame: int = 0


def event_id(edge: TemporalEdge) -> str:
    return f"{edge.relation}:{edge.source_id}:{edge.target_id}:{edge.timestamp}"


class SemanticDelta(BaseModel):
    """VLM-facing extraction contract (§4.3). Entities are echoed for provenance, not generated (D4)."""

    entities: list[Entity]
    relationships: list[VLMRelation]


def make_semantic_delta_model(schema: SkillSchema) -> type[SemanticDelta]:
    """SemanticDelta subclass whose `relation` field is constrained to the schema's instant verbs.

    Out-of-vocabulary verbs become validation errors, which is what keeps the ontology closed (§4.3).
    Durative relations are excluded on purpose — see SkillSchema.instant_relation_names.
    """
    valid = schema.instant_relation_names

    class ScopedVLMRelation(VLMRelation):
        @field_validator("relation")
        @classmethod
        def _relation_in_vocabulary(cls, v: str) -> str:
            if v not in valid:
                raise ValueError(f"relation {v!r} not in schema vocabulary {sorted(valid)}")
            return v

    class ScopedSemanticDelta(SemanticDelta):
        relationships: list[ScopedVLMRelation]

    return ScopedSemanticDelta
